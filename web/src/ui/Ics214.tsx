// FEMA ICS-214 (Activity Log), the form US incident command teams already file every operational period.
// Entries are built by code from the records; the cloud only drafts the short narrative, from structured data.
import { useState } from 'preact/hooks';
import { getGenerativeModel, InferenceMode } from 'firebase/ai';
import { assess } from '../core/rules';
import type { Household } from '../core/types';
import { firebase, type LiveConfig } from '../firebase';
import { byteLength, logCall, readLedger } from '../ledger';
import { INCIDENT_ID, type Attempt, type SelfReport } from '../store';
import { assertCloudSafe } from '../core/payload';
import { Icon } from '../site/icons';
import { INCIDENT_LABEL, PRIORITY_TEXT } from './common';

interface Row { at: number; text: string }

export function buildIcsRows(list: Household[], attempts: Attempt[], reports: SelfReport[], label: (id: string | null) => string, cfg: LiveConfig, now: number): Row[] {
  const rows: Row[] = [];
  for (const h of list) {
    const a = assess(h, cfg.incidentType, cfg.rulebook, h.reportedAt, now);
    rows.push({ at: h.reportedAt, text: `Visited ${label(h.buildingId)} (visit ${h.visits}): ${PRIORITY_TEXT[a.priority]}${a.hazards.length ? ` · ${a.hazards.map((z) => z.label).join('; ')}` : ' · no time-critical need found'} · captured ${h.source === 'on_device' ? 'with on-device AI' : 'by tap form'}` });
  }
  for (const t of attempts) rows.push({ at: t.at, text: `No answer at ${label(t.buildingId)}. Door-hanger left (code ${t.token.slice(0, 4)}-…). Recheck scheduled.` });
  for (const r of reports) rows.push({ at: r.at, text: `Resident self-report from ${label(r.buildingId)}: ${r.status === 'ok' ? 'OK' : `needs help (${r.needs.join(', ') || 'unspecified'})`}, ${r.people} in home.` });
  for (const e of readLedger().filter((x) => x.task === 'runsheet' && x.source === 'in_cloud')) rows.push({ at: e.at, text: 'Run sheets generated for field teams (cloud, structured records only).' });
  return rows.sort((a, b) => a.at - b.at);
}

export function Ics214Button(props: { list: Household[]; attempts: Attempt[]; reports: SelfReport[]; label: (id: string | null) => string; cfg: LiveConfig; now: number; teams: number }) {
  const [open, setOpen] = useState(false);
  return (
    <>
      <button class="btn ghost" onClick={() => setOpen(true)}><Icon name="book" size={16} /> ICS-214 activity log</button>
      {open && <Ics214 {...props} onClose={() => setOpen(false)} />}
    </>
  );
}

function Ics214({ list, attempts, reports, label, cfg, now, teams, onClose }: Parameters<typeof Ics214Button>[0] & { onClose: () => void }) {
  const rows = buildIcsRows(list, attempts, reports, label, cfg, now);
  const [narrative, setNarrative] = useState('');
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState('');
  const start = rows[0]?.at ?? now;
  const fmt = (t: number) => new Date(t).toLocaleString([], { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' });

  async function draft() {
    setErr(''); setBusy(true);
    const f = firebase();
    try {
      if (!f) throw new Error('Firebase not configured.');
      if (!cfg.cloudEnabled) throw new Error('Cloud is switched off by the coordinator.');
      const input = { incident: INCIDENT_LABEL[cfg.incidentType], teams, entries: rows.map((r) => ({ time: new Date(r.at).toISOString().slice(11, 16), activity: r.text })) };
      assertCloudSafe(input);
      const prompt = `Write the "notable activities" summary for a FEMA ICS-214 activity log, in 4-6 plain sentences: homes visited, urgent needs and how many are overdue, homes with no answer and door-hangers left, resident check-ins, and what the next operational period must prioritise. Use only the entries. No names. Not medical advice.\n${JSON.stringify(input)}`;
      const model = getGenerativeModel(f.ai, { mode: InferenceMode.ONLY_IN_CLOUD, inCloudParams: { model: cfg.cloudModel, generationConfig: { maxOutputTokens: 400, temperature: 0.2 } } });
      const t0 = performance.now();
      const res = await model.generateContent(prompt);
      logCall({ task: 'ics214', mode: 'ONLY_IN_CLOUD', source: 'in_cloud', ms: Math.round(performance.now() - t0), bytesUp: byteLength(prompt), doorstep: false, reason: 'ICS-214 narrative needs the whole operational period across all volunteers. Structured log lines only.' });
      setNarrative(res.response.text().trim());
    } catch (e) { setErr((e as Error).message); } finally { setBusy(false); }
  }

  return (
    <div class="modal" role="dialog" aria-label="ICS-214 activity log">
      <div class="modal-body ics-wrap">
        <div class="ics" id="ics-print">
          <div class="ics-title"><b>ACTIVITY LOG (ICS 214)</b><span>Generated by Muster · {fmt(now)}</span></div>
          <table class="ics-grid"><tbody>
            <tr><td><small>1. Incident name</small>{INCIDENT_ID} ({INCIDENT_LABEL[cfg.incidentType]})</td><td><small>2. Operational period</small>{fmt(start)} to {fmt(now)}</td></tr>
            <tr><td><small>3. Name / 4. ICS position</small>______________________</td><td><small>5. Home agency / unit</small>______________________</td></tr>
            <tr><td colSpan={2}><small>6. Resources assigned</small>{teams} field team(s) · {new Set(list.map((h) => h.reportedBy)).size} volunteer device(s) · rulebook {cfg.rulebook.version}</td></tr>
          </tbody></table>
          <div class="ics-sec">7. Activity log</div>
          <table class="ics-log"><thead><tr><th>Date/time</th><th>Notable activities</th></tr></thead>
            <tbody>{rows.length ? rows.map((r, i) => <tr key={i}><td>{fmt(r.at)}</td><td>{r.text}</td></tr>) : <tr><td colSpan={2}>No activity yet.</td></tr>}</tbody>
          </table>
          {narrative && <><div class="ics-sec">Summary (drafted by cloud AI from the entries above; review before filing)</div><p class="ics-narr">{narrative}</p></>}
          <div class="ics-foot">8. Prepared by: ______________________ Signature: __________ · Needs intake and logistics only. Not medical advice.</div>
        </div>
        {err && <p class="error">{err}</p>}
        <div class="actions">
          <button class="btn ghost" disabled={busy || !rows.length} onClick={draft}><Icon name="cloud" size={16} /> {busy ? 'Drafting…' : narrative ? 'Redraft summary' : 'Draft summary (cloud)'}</button>
          <button class="btn ghost" onClick={() => { document.body.classList.add('print-ics'); print(); document.body.classList.remove('print-ics'); }}><Icon name="book" size={16} /> Print / save PDF</button>
          <button class="btn primary" onClick={onClose}>Close</button>
        </div>
      </div>
    </div>
  );
}
